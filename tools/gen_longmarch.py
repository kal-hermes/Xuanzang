def densify(points):
    """Indicative corridor: densify a [lon,lat] chain every ~0.12°."""
    route = []
    for i, p in enumerate(points):
        route.append([p[0], p[1]])
        if i + 1 < len(points):
            q = points[i + 1]
            d = math.hypot(q[0] - p[0], q[1] - p[1])
            n = max(2, int(d / 0.12))
            for k in range(1, n):
                f = k / n
                route.append([round(p[0] + (q[0] - p[0]) * f, 4),
                              round(p[1] + (q[1] - p[1]) * f, 4)])
    return route

